SET NOCOUNT ON;
SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED;

DECLARE @EndUTC   DATETIME = GETUTCDATE();
DECLARE @StartUTC DATETIME = DATEADD(MINUTE, -3, @EndUTC);

IF OBJECT_ID('tempdb..#Units') IS NOT NULL DROP TABLE #Units;
IF OBJECT_ID('tempdb..#TailEvents') IS NOT NULL DROP TABLE #TailEvents;

SELECT
    m.MACHINE_OID,
    UPPER(LTRIM(RTRIM(m.NAME))) AS TRUCK
INTO #Units
FROM [msmodel_rep].[dbo].[MACHINE] m WITH (NOLOCK)
WHERE m.NAME IS NOT NULL
  AND (
      m.NAME LIKE 'CB%' OR
      m.NAME LIKE 'HB%' OR
      m.NAME LIKE 'KB%' OR
      m.NAME LIKE 'CT%' OR
      m.NAME LIKE 'KT%'
  );

-- Baca ekor terbaru Clustered PK (EVENT_OID DESC) agar 100% Index Seek tanpa full table scan
SELECT TOP (80000)
    E.MACHINE_OID,
    E.EVENTSOURCE,
    E.TIMESTAMP_UTC,
    E.CLASS_ID,
    E.SATELLITES
INTO #TailEvents
FROM [mshist_rep].[dbo].[PRODUCTION_EVENT] E WITH (NOLOCK)
ORDER BY E.EVENT_OID DESC;

SELECT
    U.MACHINE_OID,
    U.TRUCK,
    DATEADD(HOUR, 8, MAX(T.TIMESTAMP_UTC)) AS TIMESTAMP_WITA,
    MAX(TRY_CAST(T.SATELLITES AS FLOAT)) AS SATELLITES
FROM #Units U
LEFT JOIN #TailEvents T
    ON (T.MACHINE_OID = U.MACHINE_OID OR UPPER(LTRIM(RTRIM(T.EVENTSOURCE))) = U.TRUCK)
   AND T.CLASS_ID = 'PositionReport'
   AND T.TIMESTAMP_UTC >= @StartUTC
   AND T.TIMESTAMP_UTC <= @EndUTC
   AND T.SATELLITES IS NOT NULL
GROUP BY U.MACHINE_OID, U.TRUCK
ORDER BY U.TRUCK ASC
OPTION (RECOMPILE);